/* ==========================================================
   CLIENT PORTAL LOGIC
   Reads all client accounts and content from clients.json.
   Do not edit this file to change content; edit clients.json instead.
   ========================================================== */
(function () {
  const DATA_URL = "clients.json";

  const $ = (sel) => document.querySelector(sel);
  const esc = (t) => String(t ?? "").replace(/[&<>"']/g, c =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  let db = null;     // full contents of clients.json
  let loadError = null;

  /* ---------- Load data ---------- */
  async function loadData() {
    try {
      const res = await fetch(DATA_URL, { cache: "no-store" });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      db = await res.json();
      document.title = `${db.settings?.portalTitle || "Client Portal"} | Dumiru Jayasekara`;
    } catch (err) {
      loadError = err;
      console.error("Could not load clients.json:", err);
    }
  }

  /* ---------- Sign in ---------- */
  function findClient(username, password) {
    const u = username.trim().toLowerCase();
    return (db?.clients || []).find(c =>
      String(c.username).toLowerCase() === u && c.password === password
    ) || null;
  }

  function onLogin(e) {
    e.preventDefault();
    const errorEl = $("#loginError");
    errorEl.textContent = "";

    if (!db) {
      errorEl.textContent = loadError
        ? "Could not load client data. Open this page through a web server, with clients.json in the same folder."
        : "Loading, please try again in a moment.";
      return;
    }

    const client = findClient($("#username").value, $("#password").value);
    if (!client) {
      errorEl.textContent = "Incorrect username or password.";
      $("#password").value = "";
      return;
    }
    showPortal(client);
  }

  /* ---------- Render overview ---------- */
  function money(n) {
    return `${db.settings?.currency || ""} ${Number(n || 0).toLocaleString("en-US")}`;
  }

  function showPortal(c) {
    $("#login").classList.add("hidden");
    $("#portal").classList.remove("hidden");
    render(c);
    window.scrollTo(0, 0);
  }

  function render(c) {
    $("#greeting").innerHTML = `Welcome back, <span>${esc(c.firstName)}</span>`;
    $("#company").textContent = c.company || "";

    const projects = c.projects || [];
    const milestones = c.milestones || [];
    const active = projects.filter(p => p.status !== "Completed").length;
    const done = milestones.filter(m => m.state === "done").length;

    $("#stats").innerHTML = [
      { l: "Active projects", v: active },
      { l: "Milestones done", v: `${done}/${milestones.length}` },
      { l: "Next delivery", v: c.nextDelivery || "-" },
      { l: "Balance due", v: money(c.balanceDue) }
    ].map((s, i) => `
      <div class="stat card fade" style="animation-delay:${0.05 + i * 0.08}s">
        <small>${esc(s.l)}</small>
        <b>${typeof s.v === "number" ? `<em>${s.v}</em>` : esc(s.v)}</b>
      </div>`).join("");

    $("#projects").innerHTML = projects.map(p => `
      <div class="project">
        <div class="project-head">
          <h3>${esc(p.title)}</h3>
          <span class="badge ${p.status === "Completed" ? "done" : ""}">${esc(p.status)}</span>
        </div>
        <p>${esc(p.desc)}</p>
        <div class="progress"><div data-w="${Number(p.progress) || 0}"></div></div>
        <div class="meta-row"><span>${Number(p.progress) || 0}% complete</span><span>${esc(p.due)}</span></div>
      </div>`).join("") || `<p class="muted">No active projects.</p>`;

    const m = c.nextMeeting || {};
    $("#nextMeeting").innerHTML = m.date ? `${esc(m.date)} <span>${esc(m.time || "")}</span>` : "No meeting scheduled";
    $("#nextNote").textContent = m.note || "";

    $("#milestoneSummary").textContent = `${done} of ${milestones.length} completed`;
    $("#milestones").innerHTML = milestones.map(ms => {
      const state = ["done", "now", "todo"].includes(ms.state) ? ms.state : "todo";
      const tag = state === "now" ? `<span class="now-tag">In progress</span>` : "";
      return `<li class="${state}">${esc(ms.title)}${tag}<small>${esc(ms.date)}</small></li>`;
    }).join("") || `<p class="muted">No milestones yet.</p>`;

    // Animate progress bars after the content appears
    setTimeout(() => {
      document.querySelectorAll(".progress div").forEach(b => {
        b.style.width = b.dataset.w + "%";
      });
    }, 400);
  }

  /* ---------- Init ---------- */
  document.addEventListener("DOMContentLoaded", () => {
    $("#loginForm").addEventListener("submit", onLogin);
    loadData();
  });
})();
